#!/bin/sh
# Mosquitto has no environment-variable substitution in its config, so the
# durability limits that must be sized per deployment are rendered here from
# environment variables into an included file, then the broker starts.
# Sizing guidance: docs/mqtt/reliability.md ("Sizing the broker queue").
set -eu

require_uint() {
    case "$2" in
        ''|*[!0-9]*) echo "mosquitto entrypoint: $1 must be a non-negative integer (got '$2')" >&2; exit 1 ;;
    esac
}

AUTOSAVE_INTERVAL="${MOSQUITTO_AUTOSAVE_INTERVAL:-60}"
MAX_QUEUED_MESSAGES="${MOSQUITTO_MAX_QUEUED_MESSAGES:-100000}"
MAX_QUEUED_BYTES="${MOSQUITTO_MAX_QUEUED_BYTES:-104857600}"
PERSISTENT_CLIENT_EXPIRATION="${MOSQUITTO_PERSISTENT_CLIENT_EXPIRATION:-1d}"

require_uint MOSQUITTO_AUTOSAVE_INTERVAL "$AUTOSAVE_INTERVAL"
require_uint MOSQUITTO_MAX_QUEUED_MESSAGES "$MAX_QUEUED_MESSAGES"
require_uint MOSQUITTO_MAX_QUEUED_BYTES "$MAX_QUEUED_BYTES"
case "$PERSISTENT_CLIENT_EXPIRATION" in
    *[0-9][hdwmy]) ;;
    *) echo "mosquitto entrypoint: MOSQUITTO_PERSISTENT_CLIENT_EXPIRATION must look like 12h, 1d, 2w (got '$PERSISTENT_CLIENT_EXPIRATION')" >&2; exit 1 ;;
esac

# Named volumes are created root-owned; the broker drops to the mosquitto
# user and must be able to write its persistence file there.
mkdir -p /mosquitto/data /mosquitto/log /mosquitto/conf.d
chown -R mosquitto:mosquitto /mosquitto/data /mosquitto/log

cat > /mosquitto/conf.d/10-durability.conf <<EOF
# Generated by docker-entrypoint.sh from environment variables — edit those, not this file.
autosave_interval ${AUTOSAVE_INTERVAL}
max_queued_messages ${MAX_QUEUED_MESSAGES}
max_queued_bytes ${MAX_QUEUED_BYTES}
persistent_client_expiration ${PERSISTENT_CLIENT_EXPIRATION}
EOF

echo "mosquitto entrypoint: autosave_interval=${AUTOSAVE_INTERVAL}s max_queued_messages=${MAX_QUEUED_MESSAGES} max_queued_bytes=${MAX_QUEUED_BYTES} persistent_client_expiration=${PERSISTENT_CLIENT_EXPIRATION}"

# Upgrade only the previously shipped ACL query, preserving secrets and any
# bespoke queries. The source config is a read-only mount; render a private copy.
# MqttAllowedTopics is created by the API's AddDeviceMqttTelemetryTopic migration.
RUNTIME_CONFIG=$(mktemp /tmp/mosquitto-bms.XXXXXX.conf)
awk '
{ sub(/\r$/, "") }
$0 == "auth_opt_pg_aclquery select \047iot/\047 || \"Username\" || \047/+/+/#\047 from \"MqttCredentials\" where \"Username\" = $1" {
    print "auth_opt_pg_aclquery select \"Topic\" from \"MqttAllowedTopics\" where \"Username\" = $1 and $2::integer in (1, 2, 4)"
    next
}
{ print }
' /etc/mosquitto/mosquitto.conf > "$RUNTIME_CONFIG"
chmod 640 "$RUNTIME_CONFIG"
chown root:mosquitto "$RUNTIME_CONFIG"
exec /usr/sbin/mosquitto -c "$RUNTIME_CONFIG"
